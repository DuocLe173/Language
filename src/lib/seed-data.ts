interface RawSeedWord {
  term: string;
  traditionalTerm?: string;
  phonetic: string;
  partOfSpeech: string;
  meaningVi: string;
  naturalContextVi: string;
  exampleTarget: string;
  examplePhonetic?: string;
  exampleVi: string;
  acceptedTranslationsVi?: string[];
  notes?: string;
  level: string;
}

function buildCard(
  lang: LanguageCode,
  topicId: TopicId,
  dayNumber: number,
  orderIndex: number,
  w: RawSeedWord
): VocabCard {
  return {
    id: `${lang}_${topicId}_d${dayNumber}_w${orderIndex}`,
    userId: DEFAULT_USER_ID,
    languageCode: lang,
    topicId,
    dayNumber,
    orderIndex,
    term: w.term,
    traditionalTerm: w.traditionalTerm,
    phonetic: w.phonetic,
    partOfSpeech: w.partOfSpeech,
    meaningVi: w.meaningVi,
    naturalContextVi: w.naturalContextVi,
    exampleTarget: w.exampleTarget,
    examplePhonetic: w.examplePhonetic,
    exampleVi: w.exampleVi,
    acceptedTranslationsVi: w.acceptedTranslationsVi,
    notes: w.notes,
    tags: [`Ngày ${dayNumber}`, w.level],
    level: w.level,
    isCompletedInTopic: false,
    state: "new",
    intervalDays: 0,
    easeFactor: 2.5,
    repetitions: 0,
    nextReviewAt: SEED_DATE,
    createdAt: SEED_DATE,
  };
}

